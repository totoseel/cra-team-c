package org.example;


public class Calc {
    public int getSum(int a, int b){
        return a+b;
    }

    public int getGop(int a, int b){
        return a * b;
    }

    public int getZegop(int a){
        return a * a;
    }

    public int getMinus(int a, int b){
        return a - b;
    }
}
